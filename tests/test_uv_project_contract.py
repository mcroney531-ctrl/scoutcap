"""
Scout's dependency and deployment environment is one uv project.

  pyproject.toml   human-owned direct dependency contract (PEP 621 + uv source)
  uv.lock          the complete exact resolution, generated by uv, never hand-edited

Streamlit Community Cloud deploys `main` / `app.py` on Python 3.14 and gives
uv.lock the highest dependency-file priority, so there is no requirements.txt
to compete with it. Before this, Scout re-resolved its transitive graph on
every install (a plain pip install backtracked for minutes through boto3),
declared Python 3.12 in files production never read while Community Cloud
ran 3.14, built its devcontainer on Python 3.11 with a second, unpinned
Streamlit install, and activated a hard-coded venv outside the repo.

This replaces test_requirements_are_pinned.py: the same contract (seven exact
ordinary pins with extras, dynasty-core the only Git source at an immutable
canonical commit) now reads pyproject.toml. Whether the lock is current with
pyproject (`uv lock --check`) is a release check that needs uv, so it is run
in the build proof, not here; what the lock *says* is checked offline below.
"""
import pathlib
import re
import tomllib
import unittest

import scripts.check_dependency_versions as cdv

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORE_SHA = "cef3c3d2b7120825110235eb2c30b4f8dd9a0247"
EXPECTED_PINS = {
    "google-adk": ("2.9.2", "[extensions]"),
    "anthropic": ("1.6.0", ""),
    "httpx": ("0.28.1", ""),
    "python-dotenv": ("1.2.3", ""),
    "streamlit": ("1.64.0", ""),
    "pandas": ("2.3.3", ""),
    "mcp": ("1.28.1", "[cli]"),
}


def _read(name):
    return (ROOT / name).read_text(encoding="utf-8")


class OneDependencySystemTest(unittest.TestCase):
    def test_uv_project_files_exist_and_competing_manifests_do_not(self):
        self.assertTrue((ROOT / "pyproject.toml").is_file())
        self.assertTrue((ROOT / "uv.lock").is_file())
        for gone in ("requirements.txt", "runtime.txt", "Pipfile", "environment.yml"):
            with self.subTest(gone):
                self.assertFalse((ROOT / gone).exists())

    def test_python_is_3_14_only(self):
        project = tomllib.loads(_read("pyproject.toml"))["project"]
        self.assertEqual(project["requires-python"], ">=3.14,<3.15")
        self.assertEqual(_read(".python-version").strip(), "3.14")
        self.assertEqual(tomllib.loads(_read("uv.lock"))["requires-python"], "==3.14.*")


class DirectContractTest(unittest.TestCase):
    def setUp(self):
        self.specs = cdv.parse_project()

    def test_seven_exact_ordinary_pins_with_extras(self):
        ordinary = {cdv.normalize_name(n): (s["value"], s["extras"])
                    for n, s in self.specs.items() if s["kind"] == "version"}
        self.assertEqual(ordinary, EXPECTED_PINS)

    def test_dynasty_core_is_the_only_git_source_at_the_canonical_commit(self):
        git = {n: s for n, s in self.specs.items() if s["kind"] == "git"}
        self.assertEqual(git, {"dynasty-core": {"kind": "git", "value": CORE_SHA, "repo": cdv.DYNASTY_CORE_REPO_URL}})
        self.assertEqual(cdv.DYNASTY_CORE_REPO_URL, "https://github.com/mcroney531-ctrl/dynasty-core")
        self.assertEqual(len(self.specs), 8)

    def test_committed_lock_matches_the_contract(self):
        lock = tomllib.loads(_read("uv.lock"))
        self.assertEqual(cdv.check_lock_data(lock, self.specs), [])
        self.assertGreater(len(lock["package"]), 100)


class DevEnvironmentsUseTheLockTest(unittest.TestCase):
    def test_devcontainer_is_3_14_and_installs_only_from_the_lock(self):
        text = _read(".devcontainer/devcontainer.json")
        self.assertIn('"image": "mcr.microsoft.com/devcontainers/python:3-3.14-bookworm"', text)
        self.assertRegex(text, r"uv==\d+\.\d+\.\d+")
        self.assertIn("uv sync --locked", text)
        self.assertIn("uv run --locked streamlit run app.py", text)
        self.assertIn("--server.enableCORS false --server.enableXsrfProtection false", text)
        self.assertNotIn("requirements.txt", text)
        self.assertIsNone(re.search(r"pip3? install[^\"]*\bstreamlit\b", text))

    def test_windows_activation_uses_the_project_venv(self):
        text = _read("activate.ps1")
        self.assertIn("uv sync --locked", text)
        self.assertIn(r".venv\Scripts\Activate.ps1", text)
        self.assertNotIn("D:\\", text)

    def test_no_tracked_file_points_at_the_old_external_venv(self):
        for name in ("activate.ps1", "mcp_server.py", "README.md", ".claude/launch.json"):
            with self.subTest(name):
                self.assertNotIn("kaggleproj312", _read(name))

    def test_readme_documents_the_locked_workflow(self):
        text = _read("README.md")
        for needle in ("uv sync --locked", "uv run --locked streamlit run app.py", "uv lock --check", "3.14"):
            with self.subTest(needle):
                self.assertIn(needle, text)


if __name__ == "__main__":
    unittest.main()
